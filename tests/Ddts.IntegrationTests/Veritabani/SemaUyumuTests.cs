using Ddts.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Npgsql;

namespace Ddts.IntegrationTests.Veritabani;

/// <summary>
/// Migration'larla kurulan veritabanı, tasarımdaki docs/db/schema.sql ile birebir aynı mı?
/// Aynı PostgreSQL sunucusunda ikinci bir veritabanına schema.sql yüklenir, iki şemanın özeti
/// (tablolar, sütun tipleri, NULL/DEFAULT, CHECK, FK, EXCLUDE, indeksler, eklentiler) karşılaştırılır.
/// Kısıt ve indeks adları karşılaştırılmaz (EF Core kendi adlarını verir); içerikleri aynı olmalı.
/// Bu test geçiyorsa schema.sql üzerinde çalışan 33 kısıt testi (docs/db) migration şeması için de geçerli.
/// </summary>
public sealed class SemaUyumuTests(ApiFactory factory) : IClassFixture<ApiFactory>
{
    private const string ReferansVeritabani = "ddts_referans";

    // Her satır şemanın bir parçasını adlardan bağımsız bir metinle anlatır.
    private const string SemaOzetiSql =
        """
        SELECT 'tablo ' || c.relname
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> '__EFMigrationsHistory'
        UNION ALL
        SELECT format('sütun %s.%s %s%s%s%s',
                      c.relname, a.attname, format_type(a.atttypid, a.atttypmod),
                      CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
                      CASE WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END,
                      CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                         WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END)
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> '__EFMigrationsHistory'
          AND a.attnum > 0 AND NOT a.attisdropped
        UNION ALL
        SELECT format('kısıt %s %s', c.relname, pg_get_constraintdef(k.oid))
        FROM pg_constraint k
        JOIN pg_class c ON c.oid = k.conrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND k.contype IN ('c', 'f', 'x') AND c.relname <> '__EFMigrationsHistory'
        UNION ALL
        SELECT 'indeks ' || regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX \S+ ON', 'CREATE \1INDEX ON')
        FROM pg_index i
        JOIN pg_class c ON c.oid = i.indrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relname <> '__EFMigrationsHistory'
        UNION ALL
        SELECT 'eklenti ' || extname
        FROM pg_extension
        WHERE extname <> 'plpgsql'
        """;

    [Fact]
    public async Task Migration_ile_kurulan_sema_schema_sql_ile_ayni()
    {
        var ct = TestContext.Current.CancellationToken;

        // API başlarken migration'lar uygulanır (Database:MigrateOnStartup = true, ApiFactory)
        await using var scope = factory.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<DdtsDbContext>();
        var migrationBaglantisi = db.Database.GetConnectionString()!;
        var referansBaglantisi = await ReferansVeritabaniKurAsync(migrationBaglantisi, ct);

        var migrationSemasi = await SemaOzetiAsync(migrationBaglantisi, ct);
        var referansSema = await SemaOzetiAsync(referansBaglantisi, ct);

        var eksik = Fark(referansSema, migrationSemasi);
        var fazla = Fark(migrationSemasi, referansSema);

        Assert.True(
            eksik.Count == 0 && fazla.Count == 0,
            "Migration şeması docs/db/schema.sql'den farklı.\n" +
            $"schema.sql'de olup migration'da olmayan ({eksik.Count}):\n  " + string.Join("\n  ", eksik) + "\n" +
            $"Migration'da olup schema.sql'de olmayan ({fazla.Count}):\n  " + string.Join("\n  ", fazla));
    }

    [Fact]
    public async Task Demo_abonelik_paketleri_migration_ile_eklenir()
    {
        var ct = TestContext.Current.CancellationToken;
        await using var scope = factory.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<DdtsDbContext>();

        var paketler = await db.SubscriptionPlans
            .OrderBy(p => p.MaxClients)
            .Select(p => new { p.Name, p.MaxClients })
            .ToListAsync(ct);

        Assert.Equal(
            new[] { "Başlangıç 10", "Standart 30", "Profesyonel 100" },
            paketler.Select(p => $"{p.Name} {p.MaxClients}"));
    }

    private static async Task<string> ReferansVeritabaniKurAsync(string migrationBaglantisi, CancellationToken ct)
    {
        await using (var yonetim = new NpgsqlConnection(migrationBaglantisi))
        {
            await yonetim.OpenAsync(ct);
            await CalistirAsync(yonetim, $"DROP DATABASE IF EXISTS {ReferansVeritabani}", ct);
            await CalistirAsync(yonetim, $"CREATE DATABASE {ReferansVeritabani}", ct);
        }

        var referansBaglantisi = new NpgsqlConnectionStringBuilder(migrationBaglantisi) { Database = ReferansVeritabani }.ConnectionString;

        await using var referans = new NpgsqlConnection(referansBaglantisi);
        await referans.OpenAsync(ct);
        var semaSql = await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "schema.sql"), ct);
        await CalistirAsync(referans, semaSql, ct);

        return referansBaglantisi;
    }

    private static async Task<List<string>> SemaOzetiAsync(string baglanti, CancellationToken ct)
    {
        await using var connection = new NpgsqlConnection(baglanti);
        await connection.OpenAsync(ct);
        await using var command = new NpgsqlCommand(SemaOzetiSql, connection);
        await using var reader = await command.ExecuteReaderAsync(ct);

        var satirlar = new List<string>();
        while (await reader.ReadAsync(ct))
        {
            satirlar.Add(reader.GetString(0));
        }

        return satirlar;
    }

    private static async Task CalistirAsync(NpgsqlConnection connection, string sql, CancellationToken ct)
    {
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync(ct);
    }

    // a'da olup b'de olmayan satırlar (aynı satır iki kez varsa ikisi de sayılır)
    private static List<string> Fark(List<string> a, List<string> b)
    {
        var kalan = b.ToList();
        var fark = new List<string>();

        foreach (var satir in a.Order())
        {
            if (!kalan.Remove(satir))
            {
                fark.Add(satir);
            }
        }

        return fark;
    }
}
